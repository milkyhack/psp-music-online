static int scale_for(int size) {
    if (size == UI_FONT_LG) {
        return 2; /* 16px — integer 8x8, readable on real PSP */
    }
    if (size == UI_FONT_MD) {
        return 2;
    }
    return 1;
}

static void icon_badge_letter(int x, int y, int s, u32 color, char letter) {
    int inner = s - 2;
    int lw = 8;
    int lh = 8;
    int tx;
    int ty;

    if (inner < 8) {
        inner = 8;
    }
    ui_gfx_round_fill(x + 1, y + 1, inner, inner, 3, 0xFF141422u);
    ui_gfx_hairline_rect(x + 1, y + 1, inner, inner, color, 220);

    tx = x + (s - lw) / 2;
    ty = y + (s - lh) / 2;
    ui_font_glyph(tx, ty, color, letter, UI_FONT_SM);
}

void ui_font_init(void) {
}

int ui_font_char_w(int size) {
    return 8 * scale_for(size);
}

int ui_font_char_h(int size) {
    return 8 * scale_for(size);
}

int ui_font_text_w(const char *s, int size) {
    int n = 0;
    int cw = ui_font_char_w(size);
    if (!s) {
        return 0;
    }
    while (*s++) {
        n += cw;
    }
    return n;
}

void ui_font_glyph(int x, int y, u32 color, char ch, int size) {
    int gy, gx;
    unsigned char c = (unsigned char)ch;
    const unsigned char *g;
    int scale = scale_for(size);

    if (c < 32 || c > 127) {
        c = '?';
    }
    g = FONT8[c - 32];
    /* Integer-scaled 8x8 only — atlas resampling was unreadable on PSP. */
    for (gy = 0; gy < 8; gy++) {
        unsigned char bits = g[gy];
        for (gx = 0; gx < 8; gx++) {
            if (bits & (0x80 >> gx)) {
                ui_gfx_fill(x + gx * scale, y + gy * scale, scale, scale, color);
            }
        }
    }
}

void ui_font_text(int x, int y, u32 color, const char *s, int size) {
    int cw;
    if (!s) {
        return;
    }
    cw = ui_font_char_w(size);
    while (*s) {
        ui_font_glyph(x, y, color, *s++, size);
        x += cw;
    }
}

void ui_font_text_clip(int x, int y, int max_w, u32 color, const char *s, int size) {
    char tmp[160];
    int cx = x;
    int cw = ui_font_char_w(size);
    int max_x = x + max_w;
    int n = 0;
    if (!s) {
        return;
    }
    while (*s && cx + cw <= max_x && n < (int)sizeof(tmp) - 1) {
        tmp[n++] = *s++;
        cx += cw;
    }
    tmp[n] = '\0';
    ui_font_text(x, y, color, tmp, size);
}

void ui_font_text_shadow(int x, int y, u32 color, u32 shadow, const char *s, int size) {
    ui_font_text(x + 1, y + 1, shadow, s, size);
    ui_font_text(x, y, color, s, size);
}

void ui_font_icon(int x, int y, int size, int icon, u32 color) {
    int s = size < 12 ? 12 : size;
    int cx = x + s / 2;
    int cy = y + s / 2;
    int t = s / 5;
    if (t < 2) {
        t = 2;
    }

    switch (icon) {
        case UI_ICON_PLAY:
            /* Triangle pointing right */
            {
                int i;
                for (i = 0; i < s - 4; i++) {
                    int half = i / 2;
                    ui_gfx_fill(x + 3 + i / 2, cy - half, 1, half * 2 + 1, color);
                }
            }
            break;
        case UI_ICON_PAUSE:
            ui_gfx_round_fill(x + 2, y + 2, t + 1, s - 4, 1, color);
            ui_gfx_round_fill(x + s - t - 3, y + 2, t + 1, s - 4, 1, color);
            break;
        case UI_ICON_STOP:
            ui_gfx_round_fill(x + 3, y + 3, s - 6, s - 6, 2, color);
            break;
        case UI_ICON_PREV:
            ui_gfx_fill(x + 2, y + 2, t, s - 4, color);
            {
                int i;
                for (i = 0; i < s - 4; i++) {
                    int half = (s - 4 - i) / 2;
                    ui_gfx_fill(x + t + 2 + i / 2, cy - half, 1, half * 2 + 1, color);
                }
            }
            break;
        case UI_ICON_NEXT:
            {
                int i;
                for (i = 0; i < s - 4; i++) {
                    int half = i / 2;
                    ui_gfx_fill(x + 2 + i / 2, cy - half, 1, half * 2 + 1, color);
                }
                ui_gfx_fill(x + s - t - 2, y + 2, t, s - 4, color);
            }
            break;
        case UI_ICON_EQ:
            icon_badge_letter(x, y, s, color, 'E');
            break;
        case UI_ICON_SHUF:
            icon_badge_letter(x, y, s, color, 'S');
            break;
        case UI_ICON_RPT:
            icon_badge_letter(x, y, s, color, 'R');
            break;
        case UI_ICON_DL:
            icon_badge_letter(x, y, s, color, 'D');
            break;
        case UI_ICON_NOTE:
            icon_badge_letter(x, y, s, color, 'M');
            break;
        case UI_ICON_GLOBE:
            icon_badge_letter(x, y, s, color, 'O');
            break;
        case UI_ICON_STAR: {
            icon_badge_letter(x, y, s, color, 'T');
            break;
        }
        case UI_ICON_WIFI:
            icon_badge_letter(x, y, s, color, 'W');
            break;
        case UI_ICON_NET:
            icon_badge_letter(x, y, s, color, 'N');
            break;
        case UI_ICON_BRUSH:
            icon_badge_letter(x, y, s, color, 'P');
            break;
        case UI_ICON_USER:
            icon_badge_letter(x, y, s, color, 'U');
            break;
        case UI_ICON_DISC:
            icon_badge_letter(x, y, s, color, 'C');
            break;
        case UI_ICON_SPEAKER:
            icon_badge_letter(x, y, s, color, 'V');
            break;
        case UI_ICON_BATTERY:
            icon_badge_letter(x, y, s, color, 'B');
            break;
        case UI_ICON_BTN_X:
            ui_gfx_ring(cx, cy, s / 2 - 1, 2, color);
            ui_gfx_line(cx - 3, cy - 3, cx + 3, cy + 3, color);
            ui_gfx_line(cx + 3, cy - 3, cx - 3, cy + 3, color);
            break;
        case UI_ICON_BTN_O:
            ui_gfx_ring(cx, cy, s / 2 - 1, 2, color);
            ui_gfx_ring(cx, cy, s / 2 - 4, 2, color);
            break;
        case UI_ICON_GEAR:
            icon_badge_letter(x, y, s, color, 'G');
            break;
        default:
            break;
    }
}
